"""The standalone tools' launcher exes (Windows): OVTFlasher.exe, OVTSniffer.exe,
OVTLogger.exe, OVTSimulator.exe and OVTMcp.exe, each a few KB that starts
``OVTSuite.exe --tool <name>`` (packaging/launcher/Launcher.cs,
ovtsuite/launcher.py, docs/UPDATES.md "One copy of the code").

    python tools/build_launchers.py build --into dist/OVTSuite
            [--cache build/launchers] [--csc PATH]
        compile each launcher whose inputs changed into the cache, then copy
        every launcher into the built app folder

    python tools/build_launchers.py adopt --from dist/OVTSuite
            [--cache build/launchers]
        after Authenticode signing: keep the signed launchers in the cache, so
        the next build copies the same bytes (and signtool skips them)

The compiler is the C# compiler of the .NET Framework 4.x every Windows 10/11
has (``%WINDIR%\\Microsoft.NET\\Framework64\\v4.0.30319\\csc.exe``; or
``OVT_CSC``). It makes a new file on every run (a fresh module id and time
stamp; this csc has no /deterministic), so a launcher is compiled only when
its inputs change -- the source, its generated constants, its icon -- and the
cached exe is reused otherwise. Its version resource is the launcher's own
(LAUNCHER_VERSION), not the app's: a launcher that does not change keeps the
same bytes from one release to the next and stays out of the delta packages.
"""

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

from ovtsuite import branding                                   # noqa: E402
from ovtsuite import launcher                                   # noqa: E402

SOURCE = os.path.join(ROOT, "packaging", "launcher", "Launcher.cs")
VERSION_INFO = os.path.join(ROOT, "packaging", "version_info.txt")
DEFAULT_CACHE = os.path.join(ROOT, "build", "launchers")

#: The launchers' own file version. Raise it when Launcher.cs changes what it
#: does (not per release: an unchanged launcher must keep its bytes).
LAUNCHER_VERSION = "1.0.0.0"

#: Each launcher's display name (FileDescription; Task Manager shows it).
MCP_TITLE = "OVT-Suite MCP server"


def launchers():
    """``[{tool, exe, title, console, icon}]`` for every launcher."""
    out = []
    for tool, exe in launcher.tool_exes().items():
        console = tool == launcher.MCP
        title = MCP_TITLE if console else branding.TOOL_NAMES[tool]
        icon = os.path.join(ROOT, "packaging", "%s_%s.ico" % (branding.PKG, tool))
        if not os.path.isfile(icon):
            icon = os.path.join(ROOT, "packaging", "%s.ico" % branding.PKG)
        out.append({"tool": tool, "exe": exe + ".exe", "title": title,
                    "console": console, "icon": icon})
    return out


def _copyright() -> str:
    try:
        text = open(VERSION_INFO, encoding="utf-8-sig").read()
    except OSError:
        return ""
    m = re.search(r"StringStruct\('LegalCopyright', '([^']*)'\)", text)
    return m.group(1) if m else ""


def _cs(s: str) -> str:
    """A C# string literal."""
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def constants_source(spec: dict) -> str:
    """The generated LauncherInfo.cs for one launcher: what it starts, and
    the assembly attributes csc turns into its version resource."""
    lines = [
        "// GENERATED by tools/build_launchers.py -- do not edit",
        "using System.Reflection;",
        "[assembly: AssemblyTitle(%s)]" % _cs(spec["title"]),
        "[assembly: AssemblyDescription(%s)]" % _cs(spec["title"]),
        "[assembly: AssemblyProduct(%s)]" % _cs(branding.APP_NAME),
        "[assembly: AssemblyCopyright(%s)]" % _cs(_copyright()),
        "[assembly: AssemblyVersion(%s)]" % _cs(LAUNCHER_VERSION),
        "[assembly: AssemblyFileVersion(%s)]" % _cs(LAUNCHER_VERSION),
        "namespace OVTSuiteLauncher",
        "{",
        "    internal static class LauncherInfo",
        "    {",
        "        public const string Tool = %s;" % _cs(spec["tool"]),
        "        public const string Title = %s;" % _cs(spec["title"]),
        "        public const string MainExe = %s;" % _cs(branding.EXE_NAME + ".exe"),
        "        public const bool IsConsole = %s;" % ("true" if spec["console"] else "false"),
        "    }",
        "}",
        "",
    ]
    return "\r\n".join(lines)


def csc_command(csc: str, spec: dict, source: str, generated: str, out: str):
    """The csc.exe command line for one launcher."""
    return [csc, "/nologo", "/noconfig", "/optimize+", "/platform:anycpu",
            "/target:%s" % ("exe" if spec["console"] else "winexe"),
            "/reference:System.dll",
            "/win32icon:%s" % spec["icon"],
            "/out:%s" % out, source, generated]


def find_csc():
    """The .NET Framework 4.x C# compiler, or None."""
    env = os.environ.get("OVT_CSC")
    if env:
        return env if os.path.isfile(env) else None
    windir = os.environ.get("WINDIR") or os.environ.get("SystemRoot") or r"C:\Windows"
    for fw in ("Framework64", "Framework"):
        p = os.path.join(windir, "Microsoft.NET", fw, "v4.0.30319", "csc.exe")
        if os.path.isfile(p):
            return p
    return None


def _sha(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def input_key(spec: dict, source: str = SOURCE) -> str:
    """What a launcher is made from: its source, constants and icon."""
    h = hashlib.sha256()
    h.update(_sha(source).encode())
    h.update(constants_source(spec).encode("utf-8"))
    h.update(_sha(spec["icon"]).encode())
    h.update(json.dumps(spec, sort_keys=True).encode("utf-8"))
    return h.hexdigest()


def _key_file(cache: str, spec: dict) -> str:
    return os.path.join(cache, spec["exe"] + ".key")


def cmd_build(args):
    os.makedirs(args.cache, exist_ok=True)
    csc = None
    for spec in launchers():
        cached = os.path.join(args.cache, spec["exe"])
        kf = _key_file(args.cache, spec)
        key = input_key(spec, args.source)
        old = open(kf).read().strip() if os.path.isfile(kf) else ""
        if old == key and os.path.isfile(cached):
            state = "unchanged"
        else:
            csc = csc or args.csc or find_csc()
            if not csc:
                sys.exit("build_launchers: no C# compiler -- the .NET Framework 4.x one is "
                         "%%WINDIR%%\\Microsoft.NET\\Framework64\\v4.0.30319\\csc.exe "
                         "(part of Windows 10/11); or set OVT_CSC")
            gen = os.path.join(args.cache, spec["tool"] + "_LauncherInfo.cs")
            with open(gen, "w", encoding="utf-8", newline="") as fh:
                fh.write(constants_source(spec))
            if os.path.exists(kf):
                os.remove(kf)                       # never vouch for a failed build
            tmp = cached + ".new"
            r = subprocess.run(csc_command(csc, spec, args.source, gen, tmp))
            if r.returncode != 0 or not os.path.isfile(tmp):
                sys.exit("build_launchers: csc failed on %s (exit %d)" % (spec["exe"], r.returncode))
            os.replace(tmp, cached)
            with open(kf, "w") as fh:
                fh.write(key + "\n")
            state = "compiled"
        if args.into:
            dest = os.path.join(args.into, spec["exe"])
            if not (os.path.isfile(dest) and _sha(dest) == _sha(cached)):
                shutil.copyfile(cached, dest)
        print("  %s (%s, %s): %s" % (spec["exe"], spec["title"],
                                     "console" if spec["console"] else "windowed", state))
    return 0


def cmd_adopt(args):
    """The launchers in the app folder (signed now) become the cached ones,
    as long as the cache still describes the same inputs."""
    for spec in launchers():
        src = os.path.join(args.frm, spec["exe"])
        cached = os.path.join(args.cache, spec["exe"])
        kf = _key_file(args.cache, spec)
        if not (os.path.isfile(src) and os.path.isfile(cached) and os.path.isfile(kf)):
            continue
        if open(kf).read().strip() != input_key(spec, args.source):
            continue
        if _sha(src) != _sha(cached):
            shutil.copyfile(src, cached)
            print("  kept the signed %s" % spec["exe"])
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("build")
    s.add_argument("--into", help="the built app folder to copy the launchers into")
    s.add_argument("--cache", default=DEFAULT_CACHE)
    s.add_argument("--csc", help="the C# compiler (default: the .NET Framework 4.x one)")
    s.add_argument("--source", default=SOURCE, help=argparse.SUPPRESS)
    s.set_defaults(fn=cmd_build)
    s = sub.add_parser("adopt")
    s.add_argument("--from", dest="frm", required=True)
    s.add_argument("--cache", default=DEFAULT_CACHE)
    s.add_argument("--source", default=SOURCE, help=argparse.SUPPRESS)
    s.set_defaults(fn=cmd_adopt)
    args = ap.parse_args(argv)
    return args.fn(args) or 0


if __name__ == "__main__":
    sys.exit(main())
