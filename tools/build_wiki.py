"""Build the help website from the same pages the app shows.

    python tools/build_wiki.py                 # build/wiki/site + dist/<app>-help-<ver>.zip
    python tools/build_wiki.py --url https://example.com/ovt-suite/help
    python tools/build_wiki.py --serve         # preview at http://127.0.0.1:8000

The site is the base app's pages (ovtsuite/data/help) plus EVERY module's
(ovtsuite/<module>/help) -- the in-app help shows only the installed ones --
laid out with the same page ids, so relative links work in both. It is built
with MkDocs and the Material theme (a build-time tool only; nothing of it ships
with the app):

    pip install "mkdocs>=1.6,<2" "mkdocs-material>=9.6,<10"

(pinned below MkDocs 2: it drops the plugin and theme system Material is built
on. The pages are plain Markdown, so moving to another generator later only
means replacing this script.)

The result is a folder of static files: no database, no PHP. On a WordPress
site, upload the folder's contents into a directory of the site (for example
``public_html/ovt-suite/help/`` with the host's file manager or SFTP).
WordPress serves real files and folders as they are, so the help sits at
``https://<your site>/ovt-suite/help/`` beside the WordPress pages; add that
address to a WordPress menu, and put it in ovtsuite/data/help/help.json as
``online_url`` so the app's help window can link to it.
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from ovtsuite import branding, helpdocs  # noqa: E402


def _nav(sections):
    out = []
    for s in sections:
        if s.children:
            kids = ([{"Overview": s.page.id + ".md"}] if s.page is not None else []) + _nav(s.children)
            out.append({s.title: kids})
        elif s.page is not None:
            out.append({s.title: s.page.id + ".md"})
    return out


def stage(out_dir, url=""):
    """Copy every page and image into ``out_dir/docs`` and write
    ``out_dir/mkdocs.yml``. Returns the HelpIndex used."""
    index = helpdocs.HelpIndex(modules="all")
    docs = os.path.join(out_dir, "docs")
    if os.path.isdir(docs):
        shutil.rmtree(docs)
    roots = [(helpdocs.BASE_DIR, "")] + [
        (d, helpdocs.MODULES_PREFIX + mid + "/") for mid, d in index.module_dirs.items()]
    for src, prefix in roots:
        for d, dirs, files in os.walk(src):
            dirs[:] = [x for x in dirs if not x.startswith((".", "_", "__pycache__"))]
            for f in files:
                if f == "help.json" or f.endswith((".pyc", ".tmp")):
                    continue
                rel = os.path.relpath(os.path.join(d, f), src).replace(os.sep, "/")
                dst = os.path.join(docs, *(prefix + rel).split("/"))
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copyfile(os.path.join(d, f), dst)
    url = url or helpdocs.settings().get("online_url", "")
    cfg = {
        "site_name": "%s Help" % branding.APP_NAME,
        "site_description": branding.APP_DESC,
        "site_url": (url.rstrip("/") + "/") if url else "",
        "copyright": "Copyright &copy; %s" % _author(),
        "docs_dir": "docs",
        "use_directory_urls": True,
        "theme": {
            "name": "material",
            "features": ["navigation.sections", "navigation.top", "search.highlight",
                         "content.code.copy"],
            "palette": [
                {"media": "(prefers-color-scheme: light)", "scheme": "default",
                 "toggle": {"icon": "material/weather-night", "name": "Dark mode"}},
                {"media": "(prefers-color-scheme: dark)", "scheme": "slate",
                 "toggle": {"icon": "material/weather-sunny", "name": "Light mode"}},
            ],
        },
        "markdown_extensions": ["tables", {"toc": {"permalink": True}}],
        "plugins": ["search"],
        "nav": _nav(index.toc()),
    }
    if not cfg["site_url"]:
        del cfg["site_url"]
    with open(os.path.join(out_dir, "mkdocs.yml"), "w", encoding="utf-8", newline="\n") as fh:
        # YAML is a superset of JSON: no YAML writer needed
        fh.write("# generated by tools/build_wiki.py -- do not edit\n")
        json.dump(cfg, fh, indent=1)
        fh.write("\n")
    return index


def _author():
    try:
        from ovtsuite import credits
        return credits.AUTHOR
    except Exception:
        return branding.ORG


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build the help website (MkDocs).")
    ap.add_argument("--out", default=os.path.join(ROOT, "build", "wiki"))
    ap.add_argument("--url", default="", help="where the site will be published "
                    "(default: online_url in ovtsuite/data/help/help.json)")
    ap.add_argument("--no-zip", action="store_true")
    ap.add_argument("--serve", action="store_true", help="preview locally instead")
    ap.add_argument("--stage-only", action="store_true",
                    help="write docs/ and mkdocs.yml only (no MkDocs needed)")
    a = ap.parse_args(argv)
    os.makedirs(a.out, exist_ok=True)
    index = stage(a.out, a.url)
    print("build_wiki: %d pages (%d from modules: %s)" % (
        len(index.pages), sum(1 for p in index.pages.values() if p.module),
        ", ".join(sorted(index.module_dirs)) or "none"))
    if a.stage_only:
        return 0
    try:
        import mkdocs  # noqa: F401
        import material  # noqa: F401
    except ImportError:
        print('build_wiki: MkDocs is not installed -- pip install "mkdocs>=1.6,<2" '
              '"mkdocs-material>=9.6,<10"')
        return 2
    cfg = os.path.join(a.out, "mkdocs.yml")
    if a.serve:
        return subprocess.call([sys.executable, "-m", "mkdocs", "serve", "-f", cfg])
    site = os.path.join(a.out, "site")
    r = subprocess.call([sys.executable, "-m", "mkdocs", "build", "--clean", "-f", cfg,
                         "-d", site])
    if r != 0:
        return r
    print("build_wiki: site in %s" % site)
    if not a.no_zip:
        dist = os.path.join(ROOT, "dist")
        os.makedirs(dist, exist_ok=True)
        zpath = os.path.join(dist, "%s-help-%s.zip" % (branding.EXE_NAME, branding.__version__))
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
            for d, _dirs, files in os.walk(site):
                for f in files:
                    p = os.path.join(d, f)
                    z.write(p, os.path.relpath(p, site))
        print("build_wiki: upload the contents of %s to your site's help folder" % zpath)
    return 0


if __name__ == "__main__":
    sys.exit(main())
